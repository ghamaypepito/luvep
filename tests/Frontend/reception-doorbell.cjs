const assert = require('node:assert/strict');
const path = require('node:path');
const Module = require('node:module');
const { JSDOM } = require('jsdom');
const { buildSync } = require('esbuild');
const dom = new JSDOM('<div id="root"></div>', { url: 'https://luvep.test/reception/synthetic' });
for (const key of ['window', 'document', 'HTMLElement', 'Event', 'MouseEvent']) global[key] = dom.window[key];
Object.defineProperty(global, 'navigator', { value: dom.window.navigator, configurable: true });
global.IS_REACT_ACT_ENVIRONMENT = true;
const React = require('react'), { act } = React, { createRoot } = require('react-dom/client');
let requests = [], pending, status, setup = [];
const empty = () => null;
function load(entry) {
    const code = buildSync({ entryPoints: [entry], bundle: true, write: false, format: 'cjs', platform: 'node', jsx: 'automatic', external: ['react', '@inertiajs/react', 'axios', 'lucide-react', 'qrcode.react'] }).outputFiles[0].text;
    const m = new Module(path.resolve(entry + '.test.cjs'), module);
    m.filename = path.resolve(entry + '.test.cjs'); m.paths = module.paths;
    m.require = name => {
        if (name === '@inertiajs/react') return { Head: empty, Link: ({ children, ...props }) => React.createElement('a', props, children), useForm: () => ({ post: url => setup.push(url), processing: false }) };
        if (name === 'axios') return { post: async (url, data) => { requests.push({ url, data }); if (status) throw { response: { status } }; return new Promise(resolve => { pending = resolve; }); } };
        if (name === 'lucide-react') return new Proxy({}, { get: () => empty });
        if (name === 'qrcode.react') return { QRCodeCanvas: ({ value }) => React.createElement('canvas', { 'data-url': value }) };
        return module.require(name);
    };
    m._compile(code, m.filename); return m.exports.default;
}
const Doorbell = load('resources/js/pages/reception/Doorbell.jsx');
const Reception = load('resources/js/pages/portal/immigration/Reception.jsx');
const root = createRoot(document.getElementById('root'));
const button = text => [...document.querySelectorAll('button')].find(b => b.textContent === text);
const click = async node => { assert.ok(node); await act(async () => node.click()); };
(async () => {
    await act(async () => root.render(React.createElement(Doorbell, { ringUrl: '/reception/synthetic' })));
    assert.equal(requests.length, 0, 'Opening QR never rings');
    await click(button('Ring reception'));
    assert.ok(button('Notifying reception…').disabled);
    assert.deepEqual(requests[0], { url: '/reception/synthetic', data: {} });
    await click(button('Notifying reception…')); assert.equal(requests.length, 1);
    await act(async () => pending({ data: { notified: true } }));
    assert.ok(button('Reception notified').disabled);
    assert.match(document.querySelector('[role="status"]').textContent, /notified/);
    await act(async () => root.render(React.createElement(Doorbell, { key: 'retry', ringUrl: '/reception/synthetic' })));
    status = 503; await click(button('Ring reception'));
    assert.match(document.querySelector('[role="alert"]').textContent, /unavailable/);
    assert.equal(button('Ring reception').disabled, false);
    status = 429; await click(button('Ring reception'));
    assert.match(document.querySelector('[role="alert"]').textContent, /wait a minute/);
    status = 500; await click(button('Ring reception'));
    assert.match(document.querySelector('[role="alert"]').textContent, /could not be sent/);
    await act(async () => root.render(React.createElement(Reception, { receptionUrl: null })));
    assert.equal(setup.length, 0); await click(button('Create reception QR'));
    assert.deepEqual(setup, ['/portal/immigration/reception']);
    await act(async () => root.render(React.createElement(Reception, { receptionUrl: 'https://luvep.test/reception/synthetic' })));
    assert.equal(document.querySelector('canvas').dataset.url, 'https://luvep.test/reception/synthetic');
    assert.equal(document.querySelector('a[target="_blank"]').href, 'https://luvep.test/reception/synthetic');
    assert.equal(button('Create reception QR'), undefined);
    assert.match(document.body.textContent, /Active Immigration managers/);
    await act(async () => root.unmount());
    console.log('Reception actual React interactions passed: no automatic ring, explicit send, pending/success/retry, unavailable/cooldown errors and QR setup.');
})().catch(error => { console.error(error); process.exitCode = 1; });
