const assert = require('node:assert/strict');
const path = require('node:path');
const Module = require('node:module');
const { JSDOM } = require('jsdom');
const { buildSync } = require('esbuild');
const React = require('react');
const { act } = React;
const dom = new JSDOM('<div id="root"></div>', { url: 'http://localhost' });
for (const key of ['window', 'document', 'HTMLElement', 'Event', 'MouseEvent']) global[key] = dom.window[key];
Object.defineProperty(global, 'navigator', { value: dom.window.navigator, configurable: true });
global.IS_REACT_ACT_ENVIRONMENT = true;
const { createRoot } = require('react-dom/client');
global.fetch = async () => ({ ok: true, json: async () => ({}) });
let settings;
const empty = () => null;
const compiled = buildSync({ entryPoints: ['resources/js/pages/portal/immigration/Engagement.jsx'], bundle: true, write: false, format: 'cjs', platform: 'node', jsx: 'automatic', external: ['react', 'react-dom', '@/*', '@inertiajs/react', 'sonner', 'lucide-react'] }).outputFiles[0].text;
const component = new Module(path.resolve('engagement-gst-test.cjs'), module);
component.require = name => {
    if (name.endsWith('/useEngagementWorkflow')) return (_id, value) => { settings = value; return {}; };
    if (name === '@inertiajs/react') return { Head: empty, Link: empty, router: {} };
    if (name === 'lucide-react') return new Proxy({}, { get: () => empty });
    if (name === 'sonner') return { toast: {} };
    if (name.startsWith('@/')) return Object.assign(empty, { AvatarPhoto: empty, confirmDialog: empty });
    return module.require(name);
};
component.filename = path.resolve('engagement-gst-test.cjs'); component.paths = module.paths; component._compile(compiled, component.filename);
const Modal = component.exports.NewEngagementModal;
const root = createRoot(document.getElementById('root'));
const props = { cases: [], documents: [], signers: [], onClose: empty };
const change = async (element, value) => act(async () => {
    Object.getOwnPropertyDescriptor(element.tagName === 'SELECT' ? dom.window.HTMLSelectElement.prototype : dom.window.HTMLInputElement.prototype, 'value').set.call(element, value);
    element.dispatchEvent(new Event('change', { bubbles: true }));
    if (element.tagName !== 'SELECT') element.dispatchEvent(new Event('input', { bubbles: true }));
});
const gst = () => [...document.querySelectorAll('select')].find(el => [...el.options].some(option => option.value === 'incl'));
const fee = () => document.querySelector('input[aria-describedby="engagement-service-fee-note"]');
const summary = () => document.querySelector('[aria-label="Service fee summary"]').textContent;
(async () => {
    await act(async () => root.render(React.createElement(Modal, props)));
    await change(document.getElementById('engagement-type'), 'initial_consultation');
    assert.equal(gst().value, 'excl'); assert.equal(settings.include_gst, false);
    assert.match(summary(), /Total amountUSD 250.00/);
    await change(gst(), 'incl'); assert.equal(settings.include_gst, true);
    assert.match(summary(), /GST \(15%\)37.50/); assert.match(summary(), /Total amountUSD 287.50/);
    await change(fee(), '123.45'); assert.equal(settings.service_fee, '123.45');
    assert.match(summary(), /Total amountUSD 141.97/);
    await change(document.getElementById('consultation-currency'), 'NZD');
    assert.equal(settings.service_currency, 'NZD');
    assert.match(summary(), /Total amountNZD 141.97/);
    await change(document.getElementById('engagement-type'), 'oia');
    assert.equal(document.getElementById('consultation-currency'), null);
    assert.equal('service_currency' in settings, false);
    await change(document.getElementById('engagement-type'), 'initial_consultation');
    assert.equal(document.getElementById('consultation-currency').value, 'NZD');
    await change(document.getElementById('consultation-currency'), 'USD');
    await change(document.getElementById('engagement-type'), 'oia');
    assert.equal(gst().value, 'incl'); assert.match(summary(), /Total amountNZD 575.00/);
    await change(gst(), 'excl'); assert.match(summary(), /GST \(15%\)0.00/); assert.match(summary(), /Total amountNZD 500.00/);
    await change(document.getElementById('engagement-type'), 'initial_consultation');
    assert.equal(gst().value, 'incl'); assert.equal(fee().value, '123.45'); assert.match(summary(), /Total amountUSD 141.97/);
    await change(document.getElementById('engagement-type'), 'oia');
    assert.equal(gst().value, 'excl');
    await act(async () => root.unmount());
    const reopened = createRoot(document.getElementById('root'));
    await act(async () => reopened.render(React.createElement(Modal, { ...props, draft: { engagement_type: 'oia', include_gst: false, engagement_settings: { service_fee: '123.45', include_gst: false } } })));
    assert.equal(gst().value, 'excl'); assert.equal(fee().value, '123.45');
    assert.equal(settings.include_gst, false); assert.equal(settings.service_fee, '123.45');
    assert.match(summary(), /Disbursements0.00/); assert.match(summary(), /Total amountNZD 123.45/);
    await act(async () => reopened.unmount());
    const nzdDraft = createRoot(document.getElementById('root'));
    await act(async () => nzdDraft.render(React.createElement(Modal, { ...props, draft: { engagement_type: 'initial_consultation', currency: 'NZD', engagement_settings: { service_fee: '300', service_currency: 'NZD', include_gst: false } } })));
    assert.equal(document.getElementById('consultation-currency').value, 'NZD');
    assert.equal(settings.service_currency, 'NZD');
    assert.match(summary(), /Total amountNZD 300.00/);
    await act(async () => nzdDraft.unmount());
    console.log('Per-service GST defaults, independent selections and reopened settings passed');
})().catch(error => { console.error(error); process.exitCode = 1; });
