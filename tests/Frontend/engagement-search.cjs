const assert = require('node:assert/strict');
const path = require('node:path');
const Module = require('node:module');
const { JSDOM } = require('jsdom');
const { buildSync } = require('esbuild');
const React = require('react');
const { act } = React;
const { createRoot } = require('react-dom/client');
const dom = new JSDOM('<div id="root"></div>', { url: 'http://localhost/portal/immigration/cases/engagement?case=123' });
for (const key of ['window', 'document', 'HTMLElement', 'Event', 'MouseEvent']) global[key] = dom.window[key];
global.IS_REACT_ACT_ENVIRONMENT = true;
const calls = [];
const compiled = buildSync({entryPoints:['resources/js/pages/portal/immigration/Engagement.jsx'],bundle:true,write:false,format:'cjs',platform:'node',jsx:'automatic',external:['react','react-dom','@/*','@inertiajs/react','sonner','lucide-react']}).outputFiles[0].text;
const component = new Module(path.resolve('engagement-search-test.cjs'), module);
const empty = () => null;
component.require = name => {
    if (name === '@inertiajs/react') return {Head:empty, Link:empty, router:{get:(...args)=>calls.push(args)}};
    if (name === 'lucide-react') return new Proxy({}, {get:()=>empty});
    if (name === 'sonner') return {toast:{}};
    if (name.startsWith('@/')) return {__esModule:true, default:empty, AvatarPhoto:empty, confirmDialog:empty};
    return module.require(name);
};
component.filename=path.resolve('engagement-search-test.cjs');component.paths=module.paths;component._compile(compiled,component.filename);
const Page=component.exports.default;
const root=createRoot(document.getElementById('root'));
(async()=>{
    await act(async()=>root.render(React.createElement(Page,{search:'Older Client'})));
    const form=document.querySelector('form[aria-label="Search Engagement"]');
    assert.ok(form);
    assert.equal(form.querySelector('input').value,'Older Client');
    await act(async()=>form.dispatchEvent(new Event('submit',{bubbles:true,cancelable:true})));
    assert.equal(calls[0][0],'/portal/immigration/cases/engagement?q=Older+Client');
    assert.equal(calls[0][2].preserveState,true);
    assert.match(document.body.textContent,/No engagement records match/);
    await act(async()=>[...document.querySelectorAll('button')].find(b=>b.textContent==='Clear').click());
    assert.equal(calls[1][0],'/portal/immigration/cases/engagement');
    assert.equal(form.querySelector('input').value,'');
    await act(async()=>[...document.querySelectorAll('button')].find(b=>b.textContent.startsWith('Activity log')).click());
    assert.equal(document.querySelector('form[aria-label="Search Engagement"]'),null);
    assert.match(document.body.textContent,/No fee changes logged/);
    await act(async()=>root.unmount());
    assert.equal(calls.some(c=>c[0].includes('/leads')),false);
    console.log('Engagement search interactions passed');
})().catch(e=>{console.error(e);process.exitCode=1;});
