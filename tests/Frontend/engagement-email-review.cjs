const assert = require('node:assert/strict');
const path = require('node:path');
const Module = require('node:module');
const { JSDOM } = require('jsdom');
const { buildSync } = require('esbuild');
const React = require('react');
const { act } = React;
const { createRoot } = require('react-dom/client');
const dom = new JSDOM('<div id="root"></div>', { url: 'http://localhost' });
for (const name of ['window', 'document', 'HTMLElement', 'HTMLDialogElement', 'Event', 'MouseEvent']) global[name] = dom.window[name];
global.IS_REACT_ACT_ENVIRONMENT = true;
HTMLDialogElement.prototype.showModal = function () { this.setAttribute('open', ''); };
HTMLDialogElement.prototype.close = function () { this.removeAttribute('open'); };
const compiled = buildSync({ entryPoints: ['resources/js/components/immigration/EngagementEmailReview.jsx'], bundle: true, write: false, format: 'cjs', platform: 'node', jsx: 'automatic', external: ['react', 'react-dom', './PdfDocumentPreview'] }).outputFiles[0].text;
const component = new Module(path.resolve('engagement-review-test.cjs'), module);
component.require = (name) => name === "./PdfDocumentPreview" ? (({url,title}) => React.createElement("iframe", {src:url,title})) : module.require(name);
component.filename = path.resolve('engagement-review-test.cjs'); component.paths = module.paths; component._compile(compiled, component.filename);
const Review = component.exports.default;
const root = createRoot(document.getElementById('root'));
const review = { token: 'review-token', to: ['client@example.test'], cc: ['team@example.test'], bcc: [], subject: 'Your consultation agreement', html: '<p>Exact email preview</p>', documents: [{ name: 'Agreement.pdf', preview_url: '/private/preview/1' }, { name: 'Invoice.pdf', preview_url: '/private/preview/2' }] };
let sends = 0, closes = 0;
const render = async (busy = false) => act(async () => root.render(React.createElement(Review, { review, busy, onSend: () => sends++, onClose: () => closes++ })));
const button = (name) => [...document.querySelectorAll('button')].find(el => el.textContent.trim() === name);
const click = async el => act(async () => el.click());
(async () => {
    await render();
    assert.equal(sends, 0, 'Opening review never sends');
    assert.equal(document.activeElement, button('Cancel'), 'Cancel receives initial focus');
    assert.match(document.querySelector('dialog').textContent, /client@example.test/);
    assert.match(document.querySelector('dialog').textContent, /Agreement.pdf/);
    assert.equal(document.querySelector('iframe[title="Email preview"]').getAttribute('srcdoc'), review.html);
    assert.equal(button('Send Email').disabled, true, 'Require deliberate email/document review');
    await click(button('Invoice.pdf'));
    assert.match(document.querySelector('iframe[title="Attachment preview"]').getAttribute('src'), /preview\/2/);
    assert.equal(sends, 0, 'Previewing an attachment never sends');
    await click(button('Cancel')); assert.equal(closes, 1); assert.equal(sends, 0);
    await act(async () => document.querySelector('dialog').dispatchEvent(new Event('cancel', { cancelable: true })));
    assert.equal(closes, 2); assert.equal(sends, 0);
    await click(document.querySelector('input[type="checkbox"]'));
    assert.equal(button('Send Email').disabled, false);
    await click(button('Send Email')); assert.equal(sends, 1);
    await render(true);
    assert.equal(button('Sending…').disabled, true);
    assert.equal(button('Cancel').disabled, true);
    await act(async () => root.unmount());
    console.log('Engagement review interactions passed');
})().catch(error => { console.error(error); process.exitCode = 1; });
