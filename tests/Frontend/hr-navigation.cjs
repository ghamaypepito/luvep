const assert = require('node:assert/strict'), path = require('node:path'), Module = require('node:module');
const { buildSync } = require('esbuild');
const compiled = buildSync({entryPoints:['resources/js/components/hr/hrNavigation.js'], bundle:true, write:false, platform:'node', format:'cjs', alias:{'@':path.resolve('resources/js')}}).outputFiles[0].text;
const mod = new Module(path.resolve('hr-navigation-test.cjs'), module); mod.filename=path.resolve('hr-navigation-test.cjs'); mod.paths=module.paths; mod._compile(compiled,mod.filename);
const {hrNavigation}=mod.exports;
global.window={location:{pathname:'/portal/hr/dashboard'}};
const staff={employee:{id:1},permissions:{},can_view_staff_status:false};
const read=(hr,url,role='sales')=>hrNavigation(hr,{role},'/portal/hr'+url);
const links=nav=>nav.groups.flatMap(g=>g.tabs.map(t=>t.href));
let nav=read(staff,'/dtr/changes?scope=mine');
assert.equal(read(staff,'/equipment').current.label,'Equipment tasks');
assert.equal(read(staff,'').section.key,'overview');
assert.equal(nav.section.key,'workspace'); assert.equal(nav.current.label,'DTR changes');
assert.equal(read(staff,'/documents?scope=mine').section.key,'information');
assert.equal(read(staff,'/equipment?scope=mine').current.label,'My equipment');
assert.ok(links(nav).includes('/portal/hr/checklists')); assert.ok(links(nav).includes('/portal/hr/milestones'));
assert.ok(links(nav).includes('/portal/hr/requests')); assert.ok(links(nav).includes('/portal/hr/policies?scope=mine'));
assert.equal(nav.groups.some(g=>g.key==='team'),false); assert.equal(nav.groups.some(g=>g.key==='settings'),false);
const admin={...staff,permissions:{people:true,'dtr.review':true,'leave.review':true,'dtr.correct':true,'policies.publish':true,'access.manage':true,audit:true,preview:true},can_view_staff_status:true,can_view_dtr_changes:true};
nav=read(admin,'/dtr/changes','admin');assert.equal(nav.section.key,'team'); assert.equal(nav.current.label,'DTR acknowledgements');
assert.equal(read(admin,'/dtr/changes?scope=mine','admin').section.key,'workspace');
assert.equal(read(admin,'/documents','admin').section.key,'team');
assert.equal(read(admin,'/documents?scope=mine','admin').section.key,'information');
assert.equal(read(admin,'/people/3/edit','admin').current.label,'People');
assert.equal(read(admin,'/policies','admin').section.key,'team');
for(const route of ['/team','/leave/review','/dtr/review','/dtr/corrections','/people','/calendar','/reports','/access','/audit','/preview'])assert.ok(links(nav).includes('/portal/hr'+route),route+' remains reachable');
const unassigned={employee:null,permissions:{}};
assert.ok(links(read(unassigned,'/profile','admin')).includes('/portal/hr/documents'));
assert.ok(links(read(unassigned,'/profile','admin')).includes('/portal/hr/equipment'));
const preview={...unassigned,employee:{id:1},preview:{read_only:true}};
assert.equal(links(read(preview,'/profile','super_admin')).includes('/portal/hr/documents'),false);
assert.equal(links(read(preview,'/profile','super_admin')).includes('/portal/hr/equipment'),false);
assert.equal(links(read(preview,'/profile','super_admin')).includes('/portal/hr/dtr/changes?scope=mine'),false);
console.log('HR navigation: personal/team scopes, My Info tools, management actions, unenrolled Admin and preview boundaries passed.');
