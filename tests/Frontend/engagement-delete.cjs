const assert = require('node:assert/strict');
const path = require('node:path');
const Module = require('node:module');
const { buildSync } = require('esbuild');
const { JSDOM } = require('jsdom');
const dom = new JSDOM('<div id="root"></div>', { url: 'https://luvep.test/portal/immigration/cases/engagement' });
for (const key of ['window', 'document', 'HTMLElement', 'Event', 'MouseEvent']) global[key] = dom.window[key];
Object.defineProperty(global, 'navigator', { value: dom.window.navigator, configurable: true });
global.IS_REACT_ACT_ENVIRONMENT = true;
const React = require('react'), { act } = React, { createRoot } = require('react-dom/client');
const empty = () => null, requests = [], confirmations = [], errors = [];
const compiled = buildSync({ entryPoints: ['resources/js/pages/portal/immigration/Engagement.jsx'], bundle: true, write: false, format: 'cjs', platform: 'node', jsx: 'automatic', external: ['react', 'react-dom', '@/*', '@inertiajs/react', 'sonner', 'lucide-react'] }).outputFiles[0].text;
const loaded = new Module(path.resolve('engagement-delete-test.cjs'), module);
loaded.filename = path.resolve('engagement-delete-test.cjs'); loaded.paths = module.paths;
loaded.require = name => {
    if (name === '@inertiajs/react') return { Head: empty, Link: empty, router: { delete: (...args) => requests.push(args) } };
    if (name === 'sonner') return { toast: { error: message => errors.push(message) } };
    if (name === 'lucide-react') return new Proxy({}, { get: () => empty });
    if (name.endsWith('/ConfirmDialog')) return { confirmDialog: options => new Promise(resolve => confirmations.push({ options, resolve })) };
    if (name.startsWith('@/')) return { __esModule: true, default: empty, AvatarPhoto: empty };
    return module.require(name);
};
loaded._compile(compiled, loaded.filename);
const Page = loaded.exports.default, root = createRoot(document.getElementById('root'));
const row = { case_id: 9, case_name: 'Synthetic Client', pack_id: 'selected-pack', is_draft: false, signed: false, documents: [{ id: 21, type_key: 'written_agreement', type_label: 'Written Agreement' }] };
const render = generated => act(async () => root.render(React.createElement(Page, { generated })));
const control = () => document.querySelector('button[title^="Delete all"]');
const click = node => act(async () => { assert.ok(node); node.click(); });
(async () => {
    await render([row]);
    await click(control());
    assert.match(confirmations[0].options.message, /Synthetic Client/);
    assert.match(confirmations[0].options.message, /Finance/);
    assert.equal(control().disabled, true);
    await click(control()); assert.equal(confirmations.length, 1, 'No competing confirmation promise');
    await act(async () => confirmations[0].resolve(false));
    assert.equal(requests.length, 0, 'Cancel does not delete');
    assert.equal(control().disabled, false);
    await click(control()); await act(async () => confirmations.at(-1).resolve(true));
    assert.equal(requests.length, 1);
    assert.equal(requests[0][0], '/admin/leads/9/engagement/documents?pack_id=selected-pack');
    assert.equal(requests[0][1].preserveState, true);
    await click(control()); assert.equal(requests.length, 1);
    const reason = 'This issued invoice is linked to Finance. Ask Finance to void it if it was issued in error.';
    await act(async () => { requests[0][1].onError({ document: reason }); requests[0][1].onFinish(); });
    assert.equal(document.querySelector('[role=alert]').textContent, reason, 'Exact server explanation remains visible');
    assert.equal(errors.at(-1), reason);
    assert.ok(control(), 'Failure does not hide the record or remove its delete control');
    assert.equal(control().disabled, false);
    await click(control()); assert.equal(document.querySelector('[role=alert]'), null, 'Retry clears stale feedback');
    await act(async () => confirmations.at(-1).resolve(true));
    await act(async () => { requests.at(-1)[1].onError({}); requests.at(-1)[1].onFinish(); });
    assert.match(document.querySelector('[role=alert]').textContent, /Please refresh and try again/);
    await click(control()); await act(async () => confirmations.at(-1).resolve(true));
    await act(async () => requests.at(-1)[1].onFinish());
    await render([]);
    assert.equal(control(), null, 'Successful server list refresh removes the row');
    await render([{ ...row, pack_id: null }]);
    await click(control()); await act(async () => confirmations.at(-1).resolve(true));
    assert.equal(requests.at(-1)[0], '/admin/leads/9/engagement/documents?pack_id=legacy');
    await act(async () => requests.at(-1)[1].onFinish());
    await act(async () => root.unmount()); dom.window.close();
    console.log('Engagement delete: exact retention reason, inline feedback, cancellation, pack scoping, confirmation/request guards, retry and refreshed removal passed.');
})().catch(async error => { console.error(error); await act(async () => root.unmount()); dom.window.close(); process.exitCode = 1; });
