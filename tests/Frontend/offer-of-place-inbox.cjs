const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const Module = require('node:module');
const { buildSync } = require('esbuild');
const { JSDOM } = require('jsdom');
const dom = new JSDOM('<div id="root"></div>', { url: 'https://luvep.test/portal/education/offers-of-place' });
for (const key of ['window', 'document', 'HTMLElement', 'Event', 'MouseEvent']) global[key] = dom.window[key];
Object.defineProperty(global, 'navigator', { value: dom.window.navigator, configurable: true });
global.IS_REACT_ACT_ENVIRONMENT = true;
const React = require('react');
const { act } = React;
const { createRoot } = require('react-dom/client');
const requests = [];
const inertia = { Head: () => null, Link: ({ children, ...props }) => React.createElement('a', props, children), router: { get: (...args) => requests.push(args) } };
const component = path.resolve('resources/js/pages/portal/education/OffersOfPlace.jsx');
const compiled = buildSync({ entryPoints: [component], bundle: true, write: false, format: 'cjs', platform: 'node', jsx: 'automatic', alias: { '@': path.resolve('resources/js') }, external: ['react', 'react-dom', '@inertiajs/react'] }).outputFiles[0].text;
const loaded = new Module(component, module); loaded.filename = component; loaded.paths = module.paths;
loaded.require = name => name === '@inertiajs/react' ? inertia : module.require(name);
loaded._compile(compiled, component);
const Page = loaded.exports.default;
const root = createRoot(document.getElementById('root'));
const input = async (el, value) => act(async () => { Object.getOwnPropertyDescriptor(dom.window.HTMLInputElement.prototype, 'value').set.call(el, value); el.dispatchEvent(new Event('input', { bubbles: true })); el.dispatchEvent(new Event('change', { bubbles: true })); });
const click = async el => act(async () => el.dispatchEvent(new MouseEvent('click', { bubbles: true })));

(async () => {
    const base = '/portal/education/offers-of-place';
    const rows = [2, 1].map(id => ({ id, client_name: 'Synthetic Student', client_code: 'SYNTHETIC', filename: `offer-${id}.pdf`, uploaded_at: '2026-11-10T10:00:00Z', status: 'Submitted', view_url: `${base}/${id}/download?inline=1`, download_url: `${base}/${id}/download` }));
    await act(async () => root.render(React.createElement(Page, { base, timezone: 'UTC', clients: 1, documents: { data: rows, links: [], total: 2 } })));
    assert.match(document.body.textContent, /2 files · 1 clients/);
    assert.match(document.body.textContent, /offer-2.pdf/);
    assert.match(document.body.textContent, /offer-1.pdf/);
    assert.match(document.body.textContent, /not when a school issued/);
    const view = [...document.querySelectorAll('a')].find(a => a.textContent === 'View');
    assert.equal(view.getAttribute('href'), `${base}/2/download?inline=1`);
    assert.equal(view.getAttribute('target'), '_blank');
    const inputs = document.querySelectorAll('input');
    await input(inputs[0], 'Synthetic'); await input(inputs[1], '2026-11-09'); await input(inputs[2], '2026-11-12');
    await act(async () => document.querySelector('form').dispatchEvent(new Event('submit', { bubbles: true, cancelable: true })));
    assert.deepEqual(requests.at(-1), [base, { search: 'Synthetic', from: '2026-11-09', to: '2026-11-12' }, { preserveScroll: true }]);
    await click([...document.querySelectorAll('button')].find(b => b.textContent === 'Clear filters'));
    assert.deepEqual(requests.at(-1), [base]);
    assert.ok([...inputs].every(el => el.value === ''));
    await act(async () => root.render(React.createElement(Page, { base, clients: 0 })));
    assert.match(document.body.textContent, /No Offer of Place files found/);
    assert.equal(document.querySelectorAll('a').length, 0);
    console.log('OOP inbox: multiple versions, counts, dates, private links, filter submission, reset and empty state passed.');
    await act(async () => root.unmount()); dom.window.close();
})().catch(async error => { console.error(error); await act(async () => root.unmount()); dom.window.close(); process.exitCode = 1; });
