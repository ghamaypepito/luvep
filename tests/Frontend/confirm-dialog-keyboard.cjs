const assert = require('node:assert/strict');
const path = require('node:path');
const Module = require('node:module');
const {buildSync} = require('esbuild');
const {JSDOM} = require('jsdom');
const React = require('react');
const {act} = React;
const {createRoot} = require('react-dom/client');
const dom = new JSDOM('<div id="root"></div>');
for(const name of ['window','document','HTMLElement','Event','KeyboardEvent']) global[name]=dom.window[name];
global.IS_REACT_ACT_ENVIRONMENT=true;
const code=buildSync({entryPoints:['resources/js/components/ui/ConfirmDialog.jsx'],bundle:true,write:false,format:'cjs',platform:'node',jsx:'automatic',external:['react','react-dom','lucide-react']}).outputFiles[0].text;
const m=new Module(path.resolve('confirm-keyboard.test.cjs'),module);m.filename=path.resolve('confirm-keyboard.test.cjs');m.paths=module.paths;
m.require=name=>name==='lucide-react'?{AlertTriangle:()=>null}:module.require(name);m._compile(code,m.filename);
const root=createRoot(document.getElementById('root'));
(async()=>{
    await act(async()=>root.render(React.createElement(m.exports.ConfirmHost)));
    let result;
    await act(async()=>{m.exports.confirmDialog({title:'Delete draft?',confirmText:'Delete draft'}).then(value=>{result=value;});});
    const cancel=[...document.querySelectorAll('button')].find(button=>button.textContent==='Cancel');
    cancel.focus();
    await act(async()=>cancel.dispatchEvent(new KeyboardEvent('keydown',{key:'Enter',bubbles:true})));
    assert.equal(result,undefined,'Enter must not globally confirm while Cancel is focused');
    await act(async()=>cancel.click());assert.equal(result,false);
    await act(async()=>{m.exports.confirmDialog({confirmText:'Delete draft'}).then(value=>{result=value;});});
    await act(async()=>[...document.querySelectorAll('button')].find(button=>button.textContent==='Delete draft').click());
    assert.equal(result,true);
    await act(async()=>{m.exports.confirmDialog().then(value=>{result=value;});});
    await act(async()=>window.dispatchEvent(new KeyboardEvent('keydown',{key:'Escape'})));assert.equal(result,false);
    await act(async()=>root.unmount());
    console.log('Confirmation keyboard tests passed: Cancel Enter cannot confirm; explicit confirm and Escape work');
})().catch(error=>{console.error(error);process.exitCode=1;});
