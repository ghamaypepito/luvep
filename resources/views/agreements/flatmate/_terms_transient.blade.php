<p class="clause"><span class="n">4.2</span> The Tenant must pay the full agreed accommodation fee for the confirmed accommodation period in advance, subject to applicable law.</p>
<p class="clause"><span class="n">4.3</span> The total accommodation fee and confirmed accommodation period will be clearly stated in the Agreement.</p>
<p class="clause"><span class="n">4.4</span> The Tenant acknowledges that the accommodation fee relates to the confirmed accommodation period reserved for the Tenant.</p>
<p class="clause"><span class="n">4.5</span> Payment must be made in full within the timeframe specified by Exalt and, where applicable, before the Tenant is provided access to the accommodation.</p>
<p class="clause"><span class="n">4.6</span> If the Tenant voluntarily chooses to leave, vacate, or cease occupying the Property before the agreed end date, early departure does not automatically create a right to a refund, reduction, or credit.</p>
<p class="clause"><span class="n">4.7</span> Any refund, adjustment, credit, or release of future obligations will be dealt with in accordance with applicable law and any written agreement between Exalt and the Tenant.</p>
<p class="clause"><span class="n">4.8</span> The Tenant must contact Exalt as soon as possible if circumstances arise that may affect their ability to remain for the confirmed accommodation period.</p>
<p class="clause"><span class="n">4.9</span> The Tenant must not transfer, assign, sublet, or give another person their accommodation without Exalt’s prior written approval and where permitted by applicable law.</p>
<p class="clause"><span class="n">4.10</span> Physical departure from the Property does not, by itself, cancel or amend the Agreement.</p>
<p class="clause"><span class="n">4.11</span> Any agreed change to the confirmed accommodation period must be confirmed in writing by Exalt.</p>
<p class="clause"><span class="n">4.12</span> Nothing in this section limits any right or obligation that cannot legally be excluded or modified.</p>

