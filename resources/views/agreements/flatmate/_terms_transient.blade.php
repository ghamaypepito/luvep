<h2 class="section">Terms &amp; Conditions</h2>


<h3 class="tc-head">1. AGREEMENT</h3>
<p class="clause"><span class="n">1.1</span> This Agreement sets out the terms under which Exalt Property Management (“Exalt”) provides the Tenant with the right to occupy the designated room or rooms and use the agreed shared facilities at the Property.</p>
<p class="clause"><span class="n">1.2</span> By signing this Agreement, the Tenant accepts and agrees to comply with:</p>
<ul class="bullets">
    <li>this Agreement;</li>
    <li>the applicable House Rules;</li>
    <li>all agreed payment obligations;</li>
    <li>reasonable instructions issued by Exalt in relation to the Property; and</li>
    <li>all applicable laws, regulations, health and safety requirements, and building requirements.</li>
</ul>
<p class="clause"><span class="n">1.3</span> This Agreement, together with the applicable House Rules and any written schedules or variations signed or accepted by the parties, forms the complete agreement between Exalt and the Tenant concerning the accommodation.</p>
<p class="clause"><span class="n">1.4</span> If there is any inconsistency between this Agreement and a House Rule, this Agreement will prevail to the extent of the inconsistency, subject always to applicable law.</p>

<h3 class="tc-head">2. PARTIES AND RIGHT OF OCCUPATION</h3>
<p class="clause"><span class="n">2.1</span> The Tenant is granted a personal and non-transferable right to occupy the designated room or rooms stated in the Agreement and to use the shared areas and facilities made available by Exalt.</p>
<p class="clause"><span class="n">2.2</span> The right of occupation is limited to the Tenant and any other occupants expressly approved and recorded in the Agreement.</p>
<p class="clause"><span class="n">2.3</span> The Tenant must not:</p>
<ul class="bullets">
    <li>transfer their right of occupation;</li>
    <li>assign the Agreement;</li>
    <li>sublet the room or Property;</li>
    <li>allow another person to permanently occupy the room;</li>
    <li>give another person exclusive possession of the room; or</li>
    <li>advertise or offer the room to another person,</li>
</ul>
<p>except with Exalt’s prior written approval and where permitted by applicable law.</p>
<p class="clause"><span class="n">2.4</span> The Tenant must not use the Property for any unlawful, commercial, hazardous, or unauthorised purpose.</p>
<p class="clause"><span class="n">2.5</span> The tenant remains responsible for the conduct of their approved occupants and guests.</p>

<h3 class="tc-head">3. IDENTIFICATION AND CONTACT INFORMATION</h3>
<p class="clause"><span class="n">3.1</span> The tenant must provide Exalt with accurate and complete identification and contact information before occupation.</p>
